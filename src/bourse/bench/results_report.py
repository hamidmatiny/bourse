def _clean(segs: dict[str, Segment], f: Facts) -> None:
    b3 = segs["final-b3"].config_cells("B3")
    b1 = segs["final-b1-b0"].config_cells("B1")
    f["table:b3_domains"] = table(
        ("domain", "cases", "grader failed"),
        domain_failures(b3),
    )
    fails = [c for c in b3 if not c.all_passed]
    f["b3.failed_cases"] = str(len(fails))
    f["b3.failed_domains"] = ", ".join(f"{d} {n}" for d, _, n in domain_failures(b3) if n)
    f["b3.failed_skills"] = ", ".join(f"{k} {v}" for k, v in failed_skills(b3).items())
    f["table:b3_failures"] = table(
        ("case", "pii.detect agent", "grader detail"),
        [(c.case_id, short(pii_subtask(c)[0]), pii_subtask(c)[2]) for c in fails],
    )
    d1 = {c.case_id: c for c in b1}
    diff = []
    for c3 in b3:
        c1 = d1.get(c3.case_id)
        if c1 is None or c1.all_passed == c3.all_passed:
            continue
        diff.append(
            (
                c3.case_id,
                c3.domain,
                short(pii_subtask(c1)[0]),
                "pass" if c1.all_passed else "fail",
                short(pii_subtask(c3)[0]),
                "pass" if c3.all_passed else "fail",
            )
        )
    f["table:b1_b3_diff"] = table(
        ("case", "domain", "B1 pii.detect agent", "B1", "B3 pii.detect agent", "B3"), diff
    )
    f["b1_b3_diff_n"] = str(len(diff))
    f["b1_b3_diff_domains"] = ", ".join(sorted({d[1] for d in diff})) or "none"
    picks = {"B1": pii_picks(b1), "B3": pii_picks(b3)}
    agents = sorted(set(picks["B1"]) | set(picks["B3"]))

    def pk(cid: str, a: str) -> tuple[str, str]:
        p = picks[cid].get(a)
        if p is None:
            return "0/100", "-"
        return f"{p[0]}/{len(b1 if cid == 'B1' else b3)}", f"{p[2]}/{p[1]}"

    f["table:pii_picks"] = table(
        ("pii.detect agent", "B1 picks", "B1 hard_pii passed", "B3 picks", "B3 hard_pii passed"),
        [(a, *pk("B1", a), *pk("B3", a)) for a in agents],
    )
    b1f = [c for c in b1 if not c.all_passed]
    f["b1.failed_domains"] = ", ".join(f"{d} {n}" for d, _, n in domain_failures(b1) if n)
    f["b1.failed_cases"] = str(len(b1f))


