def _setup(segs: dict[str, Segment], hw: HostHardware, f: Facts) -> None:
    p = segs["final-suite"].summary.provenance
    f["commit"] = p.git_sha
    f["commit12"] = p.git_sha[:12]
    f["manifest"] = p.manifest_sha256 or "-"
    f["manifest12"] = (p.manifest_sha256 or "-")[:12]
    ((model, digest),) = p.model_digests.items()
    f["model"] = model
    f["model_digest"] = digest
    f["ollama_env"] = ", ".join(f"`{k}={v}`" for k, v in sorted(p.ollama_env.items()))
    f["generator_version"] = p.generator_version
    f["grader_version"] = p.grader_version
    f["hw_model"] = dash(hw.model)
    f["hw_cpu"] = dash(hw.cpu)
    f["hw_cpus"] = dash(hw.cpu_count)
    f["hw_mem_gib"] = "-" if hw.memory_bytes is None else f"{hw.memory_bytes / 2**30:.0f}"
    f["hw_os"] = hw.os
    f["ollama_version"] = dash(hw.ollama_version)
    f["docker_version"] = dash(hw.docker_version)
    first = min(s.summary.provenance.at for s in segs.values())
    last = max(s.summary.provenance.at for s in segs.values())
    f["first_segment_at"] = first.strftime("%Y-%m-%d %H:%MZ")
    f["last_segment_at"] = last.strftime("%Y-%m-%d %H:%MZ")
    samples = battery = low = therm = 0
    loads: list[float] = []
    rows = []
    for name, s in segs.items():
        h = s.summary.host
        n_cells = len(s.cells)
        n_adv = len(s.rows)
        what = f"{n_cells} cells" if n_cells else f"{n_adv} adversary rows"
        configs = ", ".join(f"{c.config_id} N={c.task_success.N}" for c in s.summary.configs)
        if h is not None:
            samples += h.samples
            battery += h.on_battery.n
            low += h.low_power.n
            therm += h.thermal_warning.n
            if h.load_1m_max is not None:
                loads.append(h.load_1m_max)
        rows.append(
            (
                f"`{name}`",
                s.summary.provenance.stack_profile,
                configs or what,
                s.summary.provenance.config_sha256[:12],
                s.summary.provenance.at.strftime("%Y-%m-%d %H:%MZ"),
                "-" if h is None else h.samples,
                "-" if h is None else f"{h.on_battery.n}/{h.low_power.n}/{h.thermal_warning.n}",
            )
        )
    f["table:segments"] = table(
        (
            "segment",
            "stack profile",
            "configs / rows",
            "config sha256",
            "started",
            "host samples",
            "battery/low-power/thermal",
        ),
        rows,
    )
    f["host_samples"] = str(samples)
    f["host_battery"] = prop(wilson(battery, samples))
    f["host_low_power"] = prop(wilson(low, samples))
    f["host_thermal"] = prop(wilson(therm, samples))
    f["host_load_max"] = f"{max(loads):.2f}" if loads else "-"
    f["segments_n"] = str(len(segs))


