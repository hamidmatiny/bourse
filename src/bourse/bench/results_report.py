# --- loading -------------------------------------------------------------------------------


@dataclass(frozen=True)
class Segment:
    name: str
    summary: BenchSummary
    records: tuple[BenchRecord, ...]
    evidence: EvidenceDigest

    @property
    def cells(self) -> list[CellResult]:
        return [r for r in self.records if isinstance(r, CellResult)]

    def config_cells(self, config_id: str) -> list[CellResult]:
        return [c for c in self.cells if c.config_id == config_id]

    def config(self, config_id: str) -> ConfigSummary:
        for c in self.summary.configs:
            if c.config_id == config_id:
                return c
        raise RenderError(f"{self.name}: no config {config_id}")

    @property
    def rows(self) -> tuple[AdversaryResult, ...]:
        return self.summary.adversary_rows


def load_segment(results_dir: Path, name: str) -> Segment:
    d = results_dir / name
    summary = BenchSummary.model_validate_json((d / "summary.json").read_text())
    lines = (d / "results.jsonl").read_text().splitlines()
    records = tuple(_RECORD.validate_json(ln) for ln in lines if ln.strip())
    evidence = EvidenceDigest.model_validate_json((d / "evidence.json").read_text())
    return Segment(name, summary, records, evidence)


def load_all(results_dir: Path) -> dict[str, Segment]:
    return {n: load_segment(results_dir, n) for n in FINAL_SEGMENTS}


# --- formatting ----------------------------------------------------------------------------


def prop(p: Proportion | None) -> str:
    return "-" if p is None else p.fmt()


def quant(q: Quantile | None, digits: int = 1) -> str:
    return "-" if q is None else q.fmt(digits)


def short(agent_id: str | None) -> str:
    return "-" if not agent_id else agent_id.split("@")[0]


def num(v: float | None, digits: int) -> str:
    return "-" if v is None else f"{v:.{digits}f}"


def dash(v: object) -> str:
    return "-" if v is None or v == "" else str(v)


def table(header: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def overlap(a: Quantile, b: Quantile) -> str:
    if None in (a.ci_low, a.ci_high, b.ci_low, b.ci_high):
        return "CI open"
    assert a.ci_low is not None and a.ci_high is not None
    assert b.ci_low is not None and b.ci_high is not None
    return "CIs overlap" if a.ci_low <= b.ci_high and b.ci_low <= a.ci_high else "CIs disjoint"


# --- derived analyses ----------------------------------------------------------------------


def exfil_agents() -> set[str]:
    return {f"{a.name}@{VENDOR}" for a in ADVERSARIES if a.behavior.startswith("exfil")}


def harm_types(cells: Sequence[CellResult]) -> dict[str, int]:
    """Output harm = grader fail on an adversary-served subtask; billing = unreported usage
    misreport; egress = cells where an exfil agent attempted egress (and how many were harm)."""
    exfil = exfil_agents()
    out = Counter[str]()
    for c in cells:
        parts = [p.strip() for p in c.harm_detail.split(";") if p.strip()] if c.harmed else []
        is_out = any(p.startswith("grader fail") for p in parts)
        is_bill = any("misreport" in p for p in parts)
        is_egress = bool(exfil & set(c.attempt_agents))
        out["harmed"] += bool(c.harmed)
        out["output"] += is_out
        out["billing"] += is_bill
        out["both"] += is_out and is_bill
        out["egress_cells"] += is_egress
        out["egress_harm"] += is_egress and any("egress" in p.lower() for p in parts)
    out["N"] = len(cells)
    return dict(out)


def output_harm_by_adversary(cells: Sequence[CellResult]) -> dict[str, Counter[str]]:
    by: dict[str, Counter[str]] = defaultdict(Counter)
    for c in cells:
        for s in c.subtasks:
            if s.agent_id and s.agent_id.endswith("@" + VENDOR) and not s.passed:
                by[short(s.agent_id)][c.domain] += 1
    return by


def pii_subtask(c: CellResult) -> tuple[str | None, bool, str]:
    for s in c.subtasks:
        if s.skill == PII_SKILL:
            return s.agent_id, s.passed, s.detail
    return None, False, ""


def poison_identity(
    mixed: Sequence[CellResult], clean: Sequence[CellResult]
) -> tuple[int, int, int, int, set[str]]:
    """poison-quiet's pii.detect grader line vs the honest agent's line on the same case in
    clean B3: (identical, served, identical among grader fails, grader fails, honest agents)."""
    by_case = {c.case_id: c for c in clean}
    same = served = fail_same = fails = 0
    honest: set[str] = set()
    for c in mixed:
        agent, passed, detail = pii_subtask(c)
        if short(agent) != "poison-quiet" or c.case_id not in by_case:
            continue
        h_agent, _, h_detail = pii_subtask(by_case[c.case_id])
        served += 1
        same += detail == h_detail
        if not passed:
            fails += 1
            fail_same += detail == h_detail
        if h_agent:
            honest.add(short(h_agent))
    return same, served, fail_same, fails, honest


def pii_picks(cells: Sequence[CellResult]) -> dict[str, tuple[int, int, int]]:
    """agent -> (pii.detect picks, hard_pii served, hard_pii passed)."""
    out: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for c in cells:
        agent, passed, _ = pii_subtask(c)
        row = out[short(agent)]
        row[0] += 1
        if c.domain == "hard_pii":
            row[1] += 1
            row[2] += passed
    return {k: (v[0], v[1], v[2]) for k, v in sorted(out.items())}


def domain_failures(cells: Sequence[CellResult]) -> list[tuple[str, int, int]]:
    total, failed = Counter[str](), Counter[str]()
    for c in cells:
        total[c.domain] += 1
        failed[c.domain] += not c.all_passed
    return [(d, total[d], failed[d]) for d in sorted(total, key=lambda d: (-failed[d], d))]


def failed_skills(cells: Sequence[CellResult]) -> Counter[str]:
    return Counter(s.skill for c in cells for s in c.subtasks if not s.passed)


