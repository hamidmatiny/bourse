def facts(results_dir: Path) -> Facts:
    segs = load_all(results_dir)
    hw = HostHardware.model_validate_json((results_dir / "host.json").read_text())
    f: Facts = {}
    steps: tuple[Callable[[], None], ...] = (
        lambda: _setup(segs, hw, f),
        lambda: _headline(segs, f),
        lambda: _suite(segs, f),
        lambda: _ablations(segs, f),
        lambda: _harm(segs, f),
        lambda: _quiet(segs, f),
        lambda: _clean(segs, f),
        lambda: _supporting(results_dir, f),
    )
    for step in steps:
        step()
    return f


def render(template: str, values: Facts) -> str:
    return f"{GENERATED_NOTE}\n\n{fill(template, values)}"


README_BEGIN = "<!-- RESULTS:BEGIN (generated by `uv run bourse bench report --results`) -->"
README_END = "<!-- RESULTS:END -->"


def fill(template: str, values: Facts) -> str:
    missing = sorted({m for m in PLACEHOLDER.findall(template) if m not in values})
    if missing:
        raise RenderError(f"template keys with no value: {', '.join(missing)}")
    return PLACEHOLDER.sub(lambda m: values[m.group(1)], template)


def update_readme(readme: str, snippet: str, values: Facts) -> str:
    """Replace the block between the RESULTS markers; refuses if the markers are missing."""
    start, end = readme.find(README_BEGIN), readme.find(README_END)
    if start < 0 or end < start:
        raise RenderError("README.md has no RESULTS:BEGIN/RESULTS:END block")
    body = fill(snippet, values).strip()
    return readme[: start + len(README_BEGIN)] + "\n" + body + "\n" + readme[end:]


@dataclass(frozen=True)
class Rendered:
    results_md: str
    readme: str


def render_all(
    results_dir: Path, template_path: Path, readme_snippet: Path, readme_path: Path
) -> Rendered:
    values = facts(results_dir)
    return Rendered(
        results_md=render(template_path.read_text(), values),
        readme=update_readme(readme_path.read_text(), readme_snippet.read_text(), values),
    )
